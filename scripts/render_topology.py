#!/usr/bin/env python3
"""Render and validate the dsco-autobot topology from the canonical registry.

Source of truth: ``libs/dsco_shared/src/dsco_shared/config/ports.py``.
This script keeps the deploy artifacts derived from it in sync so the
app-vs-compose port drift that previously hid bugs cannot recur.

Commands:
    toml        Write libs/service_registry.toml (ops reference).
    env         Write infra/docker/.env.example for --mode (local|docker|modal).
    prometheus  Write infra/docker/prometheus.yml scrape targets.
    check       Verify docker-compose port mappings match the registry;
                exits non-zero on mismatch (use as a CI gate).
    all         toml + env + prometheus + check.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

# Bootstrap import without requiring an install (for first run / CI).
_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(_ROOT / "libs" / "dsco_shared" / "src"))

from dsco_shared.config.ports import DOCKER_NAMES, INFRA_PORTS, SERVICE_PORTS  # noqa: E402

# compose container name -> canonical service key
_CONTAINER_TO_KEY = {v: k for k, v in DOCKER_NAMES.items()}


def _canonical_for_compose_service(svc_name: str, container_name: str | None) -> str | None:
    if container_name and container_name in _CONTAINER_TO_KEY:
        return _CONTAINER_TO_KEY[container_name]
    if svc_name in _CONTAINER_TO_KEY:
        return _CONTAINER_TO_KEY[svc_name]
    return svc_name if svc_name in SERVICE_PORTS else None


def render_toml() -> str:
    lines = ["# AUTO-GENERATED by scripts/render_topology.py — do not edit by hand.",
             "# Source of truth: libs/dsco_shared/src/dsco_shared/config/ports.py", ""]
    lines.append("[services]")
    for name, port in SERVICE_PORTS.items():
        lines.append(f'{name.replace("-", "_")} = {{ port = {port}, key = "{name}" }}')
    lines += ["", "[infra]"]
    for name, port in INFRA_PORTS.items():
        lines.append(f'{name.replace("-", "_")} = {port}')
    return "\n".join(lines) + "\n"


def _host_for(name: str, mode: str) -> str:
    if mode == "docker":
        return DOCKER_NAMES.get(name, name)
    return "localhost"


def render_env(mode: str) -> str:
    lines = [
        f"# AUTO-GENERATED by scripts/render_topology.py --mode {mode}",
        f"DSCO_DEPLOY_MODE={mode}",
        "",
        "# Application service URLs (override per environment as needed).",
    ]
    for name in SERVICE_PORTS:
        env_key = f"DSCO_{name.upper().replace('-', '_')}_URL"
        scheme = "ws" if name == "realtime" else "http"
        lines.append(f'{env_key}={scheme}://{_host_for(name, mode)}:{SERVICE_PORTS[name]}')
    lines += ["", "# Infrastructure"]
    infra_host = (lambda c: c) if mode == "docker" else (lambda c: "localhost")
    lines.append(f'REDIS_URL=redis://{infra_host("redis")}:6379')
    lines.append(f'DATABASE_URL=postgresql://{infra_host("postgres")}:5432/dsco')
    lines.append(f'TEMPORAL_ADDRESS={infra_host("temporal")}:7233')
    return "\n".join(lines) + "\n"


def render_prometheus() -> str:
    lines = ["# AUTO-GENERATED by scripts/render_topology.py", "global:", "  scrape_interval: 15s", "", "scrape_configs:"]
    for name, port in SERVICE_PORTS.items():
        host = DOCKER_NAMES.get(name, name)
        lines.append(f"  - job_name: '{name}'")
        lines.append(f"    static_configs: - targets: ['{host}:{port}']")
    return "\n".join(lines) + "\n"


def check_compose(compose_path: Path) -> int:
    try:
        import yaml  # type: ignore
    except ImportError:
        print("PyYAML not installed — skipping compose check.", file=sys.stderr)
        return 0
    if not compose_path.exists():
        print(f"compose file not found: {compose_path}", file=sys.stderr)
        return 0
    data = yaml.safe_load(compose_path.read_text()) or {}
    services = data.get("services", {})
    mismatches: list[str] = []
    for svc, spec in services.items():
        ports = spec.get("ports", []) or []
        container = spec.get("container_name")
        key = _canonical_for_compose_service(svc, container)
        if key is None or not ports:
            continue
        for mapping in ports:
            m = str(mapping)
            # accept "H:C" or "C" forms
            container_port = int(m.split(":")[-1].split("/")[0])
            expected = SERVICE_PORTS.get(key)
            if expected is not None and container_port != expected:
                mismatches.append(
                    f"  {svc} (={key}) maps {m}, registry expects :{expected}"
                )
    if mismatches:
        print(f"compose/registry port mismatches ({len(mismatches)}):", file=sys.stderr)
        for m in mismatches:
            print(m, file=sys.stderr)
        return 1
    print("compose ports match registry ✓")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("command", choices=["toml", "env", "prometheus", "check", "all"])
    ap.add_argument("--mode", default="docker", choices=["local", "docker", "modal"])
    args = ap.parse_args()

    rc = 0
    if args.command in ("toml", "all"):
        out = _ROOT / "libs" / "service_registry.toml"
        out.write_text(render_toml())
        print(f"wrote {out}")
    if args.command in ("env", "all"):
        out = _ROOT / "infra" / "docker" / ".env.example"
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(render_env(args.mode))
        print(f"wrote {out} (mode={args.mode})")
    if args.command in ("prometheus", "all"):
        out = _ROOT / "infra" / "docker" / "prometheus.yml"
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(render_prometheus())
        print(f"wrote {out}")
    if args.command in ("check", "all"):
        rc = check_compose(_ROOT / "infra" / "docker" / "docker-compose.full.yml")
    return rc


if __name__ == "__main__":
    raise SystemExit(main())
